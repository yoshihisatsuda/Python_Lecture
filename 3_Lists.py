#リストの作成
numbers = []
strings = []
names = ["John", "Eric", "Jessica"]

#リストに要素を追加(append)
numbers.append(1)
numbers.append(2)
numbers.append(3)

strings.append("hello")
strings.append("world")

#変数の宣言
second_name = names[1]

#リストの内容を出力
print(numbers)
print(strings)
print("The second name on the names list is %s" % second_name)
